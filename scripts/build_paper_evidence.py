def stem(slug,model,ds):
 env='tf5180' if slug=='tap' and model!='MiniCPM4_8B' else 'tf4576'
 return f'{slug}__{model}__{ds}__{env}'

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def write_csv(path,rows):
 with path.open('w',newline='',encoding='utf-8') as f:
  w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader()
  for row in rows:w.writerow({k:json.dumps(v,ensure_ascii=False) if isinstance(v,(dict,list)) else v for k,v in row.items()})

def table(name,label,caption,cols,header,rows,wide=False):
 env='table*' if wide else 'table'
 lines=['% Generated by scripts.build_paper_evidence; edit the generator.',f'\\begin{{{env}}}[tb]',r'\centering',r'\footnotesize',r'\setlength{\tabcolsep}{3pt}',
        f'\\caption{{{caption}}}',f'\\label{{{label}}}',f'\\begin{{tabular}}{{@{{}}{cols}@{{}}}}',r'\toprule',header+r' \\',r'\midrule']
 lines+=[' & '.join(map(str,row))+r' \\' for row in rows]
 lines +=[r'\bottomrule',r'\end{tabular}',f'\\end{{{env}}}']
 (TEX/(name+'.tex')).write_text('\n'.join(lines)+'\n')

def scientific(x):
 if x>=.01:return f'{x:.3g}'
 b,e=f'{x:.1e}'.split('e');return f'${b}\\times10^{{{int(e)}}}$'

