def plot_variant_tradeoff(mechanism: dict) -> None:
    specs = (("rank50", "Paired", BLUE, "o", "D"),
             ("medusa", "Medusa", RED, "D", "M"),
             ("eagle", "EAGLE", VIOLET, "X", "E"))
    for model, _, short in MODELS:
        fig, ax = plt.subplots(figsize=(2.45, 1.78), constrained_layout=True)
        ax.axhline(float(mechanism["target_asr_pct"][model.lower()]), color=NEUTRAL,
                   linestyle=(0, (3, 2)), linewidth=0.8, label="Target")
        for source, label, color, marker, abbrev in specs:
            cell = mechanism["cells"][f"{source}|{model.lower()}"]
            x = float(cell["acceptance_pct"])
            y = float(cell["asr_pct"])
            ax.scatter([x], [y], color=color, marker=marker, s=28,
                       edgecolor="white", linewidth=0.5, label=label, zorder=3)
            ax.annotate(abbrev, (x, y), xytext=(3, 3), textcoords="offset points",
                        fontsize=5.4, fontweight="bold", color=color)
        ax.set_xlim(10, 100)
        ax.set_ylim(0, 100)
        ax.set_xlabel("Acceptance (%)")
        ax.set_ylabel("ASR (%)")
        ax.grid(True, color=GRID, linewidth=0.45, linestyle=(0, (1, 2)))
