def pooled_asr(evidence: dict, model: str, slug: str) -> float:
    positive = 0
    total = 0
    for dataset, _ in DATASETS:
        judge = evidence["cells"][f"{slug}|{model}|{dataset}"]["judges"]["gptoss"]
        positive += int(judge["positive"])
        total += int(judge["n_total"])
    return 100 * positive / total


