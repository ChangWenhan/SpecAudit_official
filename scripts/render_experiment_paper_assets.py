def variant_metric_cell(value: dict) -> str:
    return f"{value['asr_pct']:.1f}\\%"


def variant_acceptance(security: dict, source: str, model: str) -> float | None:
    model_key = model.lower()
    values = []
    for dataset, _ in DATASETS:
        cell = security[f"{source}|{model_key}|{dataset}"]
        if cell["acceptance_pct"] is not None:
            values.append((cell["acceptance_pct"], cell["n"]))
    if not values:
        return None
    return sum(value * n for value, n in values) / sum(n for _, n in values)


