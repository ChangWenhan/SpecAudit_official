def acceptance_curve(model: str, dataset: str, slug: str, nmax: int = 20):
    path = ROOT / "results" / f"{slug}__{model}__{dataset}__tf4576.jsonl"
    accepted, evaluated, records, empty, _ = profile(path, nmax)
    if not records or empty == records:
        raise ValueError(f"no acceptance data in {path}")
    return np.asarray(accepted, dtype=int), np.asarray(evaluated, dtype=int)


