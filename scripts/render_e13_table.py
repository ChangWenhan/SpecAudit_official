#!/usr/bin/env python3
"""Render the final three-seed E13 main table from analysis JSON."""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path


MODELS = (("Qwen3_4B", "Qwen3-4B"), ("Gemma_3_4B", "Gemma-3-4B"),
          ("MiniCPM4_8B", "MiniCPM4-8B"))
DATASETS = (("jbb", "JBB"), ("advbench", "Adv."), ("strongreject", "SR"))
CONDITIONS = (("target", "Target"), ("draft", "Draft"),
              ("rank50", r"\textbf{Draft + rank-50}"),
              ("exact", "Draft + exact"),
              ("securesd", "Draft + SecureSD"),
              ("tap", r"TAP$^{\dagger}$"), ("flipattack", "FlipAttack"))


def atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                     prefix="." + path.name, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(path)


def format_rate(row: dict) -> str:
    mean = float(row["mean_pct"])
    low, high = map(float, row["minmax"])
    return rf"\shortstack{{{mean:.1f}\\{{\scriptsize [{low:.1f}, {high:.1f}]}}}}"


def render(analysis: dict, judge: str = "gptoss") -> str:
    asr = {}
    for row in analysis.get("asr", []):
        if row.get("judge") != judge:
            continue
        key = (row["model"], row["dataset"], row["condition"])
        if key in asr:
            raise ValueError(f"duplicate ASR row: {key}")
        asr[key] = row
    utility = {(row["model"], row["condition"]): row for row in analysis.get("utility", [])}
    expected_asr = {(model, dataset, condition)
                    for model, _ in MODELS for dataset, _ in DATASETS
                    for condition, _ in CONDITIONS}
    expected_utility = {(model, condition)
                        for model, _ in MODELS for condition, _ in CONDITIONS}
    if set(asr) != expected_asr:
        raise ValueError(f"ASR grid mismatch: missing={sorted(expected_asr - set(asr))}, "
                         f"unexpected={sorted(set(asr) - expected_asr)}")
    if set(utility) != expected_utility:
        raise ValueError(f"utility grid mismatch: missing={sorted(expected_utility - set(utility))}, "
                         f"unexpected={sorted(set(utility) - expected_utility)}")
    lines = [
        "% Generated by scripts/render_e13_table.py; edit the generator.",
        r"\begin{table*}[t]", r"\centering", r"\scriptsize",
        r"\setlength{\tabcolsep}{2pt}",
        (r"\caption{Three-seed primary-judge ASR and IFEval utility. Each ASR cell is "
         r"the mean over seeds 0/1/2 with the observed min--max range below it. "
         r"IFEval is strict prompt-level accuracy; TAP and FlipAttack reuse the "
         r"Target-only utility because they do not change the served model. "
         r"$^{\dagger}$Seed-0 TAP uses its legacy 150-token budget; seeds 1/2 "
         r"use 160 tokens.}"),
        r"\label{tab:main}", r"\begin{tabular}{l cccc|cccc|cccc}", r"\toprule",
        (r"& \multicolumn{4}{c|}{Qwen3-4B} & \multicolumn{4}{c|}{Gemma-3-4B} "
         r"& \multicolumn{4}{c}{MiniCPM4-8B} \\"),
        r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}\cmidrule(lr){10-13}",
        r"Condition & JBB & Adv. & SR & IFEval & JBB & Adv. & SR & IFEval & JBB & Adv. & SR & IFEval \\",
        r"\midrule",
    ]
    for condition, label in CONDITIONS:
        row = [label]
        for model, _ in MODELS:
            row.extend(format_rate(asr[model, dataset, condition])
                       for dataset, _ in DATASETS)
            row.append(format_rate(utility[model, condition]))
        lines.append(" & ".join(row) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--judge", choices=("gptoss", "guard"), default="gptoss")
    args = parser.parse_args()
    tex = render(json.loads(args.analysis.read_text()), args.judge)
    atomic_text(args.out, tex)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
