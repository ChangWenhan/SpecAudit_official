#!/usr/bin/env python3
"""Summarize and render the one-seed speculative-variant security experiment."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from src.result_io import read_jsonl


MODELS = (("qwen3_4b", "Qwen3_4B", "Qwen3-4B"),
          ("gemma_3_4b", "Gemma_3_4B", "Gemma-3-4B"),
          ("minicpm4_8b", "MiniCPM4_8B", "MiniCPM4-8B"))
DATASETS = (("jbb", "JBB"), ("advbench", "Adv."),
            ("strongreject", "SR"))
VARIANTS = (("medusa", "Medusa-style", "Medusa"),
            ("eagle", "EAGLE-style", "EAGLE"))


def cell(successes: int, total: int, acceptance: float | None) -> dict:
    return {"unsafe": successes, "n": total, "asr_pct": 100 * successes / total,
            "acceptance_pct": acceptance}


def load_variants(root: Path) -> dict:
    rows = {}
    for variant, _, _ in VARIANTS:
        for model, _, _ in MODELS:
            for dataset, _ in DATASETS:
                judged = root / variant / model / f"{dataset}.gptoss.jsonl"
                values = read_jsonl(judged)
                unsafe = sum(row["guard_gptoss"]["safety"] == "unsafe" for row in values)
                rates = [row["stats"]["accepted_tokens"] / row["stats"]["proposed_tokens"]
                         for row in values if row["stats"]["proposed_tokens"]]
                acceptance = 100 * sum(rates) / len(rates) if rates else None
                rows[variant, model, dataset] = cell(unsafe, len(values), acceptance)
    return rows


def load_main(main_analysis: Path, raw_root: Path) -> dict:
    analysis = json.loads(main_analysis.read_text())
    rows = {}
    for model, analysis_model, _ in MODELS:
        for dataset, _ in DATASETS:
            for condition in ("target", "rank50"):
                match = [row for row in analysis["asr"]
                         if row["model"] == analysis_model
                         and row["dataset"] == dataset
                         and row["condition"] == condition
                         and row["judge"] == "gptoss"]
                if len(match) != 1:
                    raise ValueError(f"expected one main row: {model}/{dataset}/{condition}")
                rate = float(match[0]["seed_values_pct"]["0"])
                n = int(analysis["datasets"][dataset])
                successes = round(n * rate / 100)
                if abs(100 * successes / n - rate) > 1e-7:
                    raise ValueError(f"non-integral main rate: {model}/{dataset}/{condition}")
                acceptance = None
                if condition == "rank50":
                    values = read_jsonl(raw_root / f"topk50__{analysis_model}__{dataset}__tf4576.jsonl")
                    acceptance = 100 * sum(float(row["accept_rate"]) for row in values) / len(values)
                rows[condition, model, dataset] = cell(successes, n, acceptance)
    return rows


def latex_cell(row: dict) -> str:
    return f"{row['asr_pct']:.1f}\\%"


def format_acceptance(value: float | None) -> str:
    return "--" if value is None else f"{value:.1f}"


def pooled_acceptance(cells: dict, key: str, model: str) -> float | None:
    values = [(row["acceptance_pct"], row["n"]) for dataset, _ in DATASETS
              if (row := cells[key, model, dataset])["acceptance_pct"] is not None]
    if not values:
        return None
    return sum(value * n for value, n in values) / sum(n for _, n in values)


def render_table(cells: dict) -> str:
    lines = [
        "% Generated by scripts/analyze_spec_variant_security.py; edit the generator.",
        r"\begin{table*}[t]", r"\centering", r"\scriptsize",
        r"\setlength{\tabcolsep}{2pt}",
        (r"\caption{One-seed primary-judge ASR and acceptance for speculative "
         r"proposal families under rank-50 verification. ASR is unsafe divided "
         r"by all responses and is reported as a one-seed point estimate without "
         r"an across-seed range. Acc. is the "
         r"mean per-request accepted-to-proposed token ratio pooled over the three "
         r"datasets. JBB, AdvBench, and StrongREJECT contain 100, 520, and 313 "
         r"responses per cell. Medusa-style and EAGLE-style use the reviewed "
         r"protocol-v2 learned-head adapters; the final row reuses the project's "
         r"paired-draft rank-50 run.}"),
        r"\label{tab:spec-variant-security}",
        r"\begin{tabular}{l cccc|cccc|cccc}", r"\toprule",
        (r"& \multicolumn{4}{c|}{Qwen3-4B} & \multicolumn{4}{c|}{Gemma-3-4B} "
         r"& \multicolumn{4}{c}{MiniCPM4-8B} \\"),
        r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}\cmidrule(lr){10-13}",
        (r"Proposal source & JBB & Adv. & SR & Acc. & JBB & Adv. & SR & Acc. "
         r"& JBB & Adv. & SR & Acc. \\"),
        r"\midrule",
    ]
    rows = (("target", "Target"),
            *((variant, label) for variant, label, _ in VARIANTS),
            ("rank50", r"\textbf{Draft + rank-50}"))
    for key, label in rows:
        values = [label]
        for model, _, _ in MODELS:
            for dataset, _ in DATASETS:
                values.append(latex_cell(cells[key, model, dataset]))
            values.append(format_acceptance(pooled_acceptance(cells, key, model)))
        lines.append(" & ".join(values) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path,
                        default=Path("results/security_variants_20261122/seed_0"))
    parser.add_argument("--main-analysis", type=Path,
                        default=Path("results/e13_analysis_20261122/e13.json"))
    parser.add_argument("--raw-root", type=Path, default=Path("results"))
    parser.add_argument("--out", type=Path,
                        default=Path("results/security_variants_20261122/analysis"))
    args = parser.parse_args()
    cells = load_variants(args.root)
    cells.update(load_main(args.main_analysis, args.raw_root))
    args.out.mkdir(parents=True, exist_ok=True)

    serializable = {"|".join(key): value for key, value in cells.items()}
    (args.out / "spec_variant_security.json").write_text(
        json.dumps(serializable, indent=2, sort_keys=True) + "\n")
    (args.out / "table_spec_variant_security.tex").write_text(render_table(cells))
    with (args.out / "spec_variant_security.csv").open("w", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(("source", "model", "dataset", "unsafe", "n", "asr_pct",
                         "acceptance_pct"))
        for key in sorted(cells):
            value = cells[key]
            writer.writerow((*key, value["unsafe"], value["n"], value["asr_pct"],
                             value["acceptance_pct"]))
    print(f"wrote {args.out / 'table_spec_variant_security.tex'}")


if __name__ == "__main__":
    main()
