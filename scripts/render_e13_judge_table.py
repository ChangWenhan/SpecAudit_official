#!/usr/bin/env python3
"""Render Table 5: primary versus auxiliary judge over 54 E13 cells."""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path


MODELS = (("Qwen3_4B", "Qwen3-4B"), ("Gemma_3_4B", "Gemma-3-4B"),
          ("MiniCPM4_8B", "MiniCPM4-8B"))
DATASETS = (("jbb", "JBB"), ("advbench", "Adv."), ("strongreject", "SR"))
CONDITIONS = (("target", "Target"), ("rank50", "Rank-50"),
              ("exact", "Exact"), ("securesd", "SecureSD"),
              ("flipattack", "FlipAttack"), ("tap", "TAP"))


def atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                     prefix="." + path.name, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(path)


def compact(row: dict) -> str:
    mean = float(row["mean_pct"])
    low, high = map(float, row["minmax"])
    return f"{mean:.1f} [{low:.1f}, {high:.1f}]"


def render(analysis: dict) -> str:
    rows = {(row["model"], row["dataset"], row["condition"], row["judge"]): row
            for row in analysis.get("asr", [])}
    expected = {(model, dataset, condition)
                for model, _ in MODELS for dataset, _ in DATASETS
                for condition, _ in CONDITIONS}
    actual = {(model, dataset, condition) for model, dataset, condition, _ in rows}
    if actual != expected or len(rows) != 2 * len(expected):
        raise ValueError("judge comparison grid mismatch")
    lines = [
        "% Generated by scripts/render_e13_judge_table.py; edit the generator.",
        r"\begin{table*}[t]", r"\centering", r"\scriptsize",
        r"\setlength{\tabcolsep}{2pt}",
        (r"\caption{Three-seed ASR under the independent gpt-oss primary judge and the "
         r"secondary, non-independent Qwen3Guard wide judge. Each cell is primary "
         r"mean [min--max] / auxiliary mean [min--max]. Draft-alone is excluded "
         r"because it is not a served decoding configuration.}"),
        r"\label{tab:judge}", r"\begin{tabular}{ll cccccc}", r"\toprule",
        r"Model & Dataset & Target & Rank-50 & Exact & SecureSD & FlipAttack & TAP \\",
        r"\midrule",
    ]
    for model, model_label in MODELS:
        for dataset, dataset_label in DATASETS:
            cells = []
            for condition, _ in CONDITIONS:
                primary = compact(rows[model, dataset, condition, "gptoss"])
                auxiliary = compact(rows[model, dataset, condition, "guard"])
                cells.append(r"\shortstack{" + primary + r"\\ " + auxiliary + "}")
            lines.append(" & ".join([model_label, dataset_label, *cells]) + r" \\")
        if model != MODELS[-1][0]:
            lines.append(r"\midrule")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    atomic_text(args.out, render(json.loads(args.analysis.read_text())))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
